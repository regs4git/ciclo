function t(key, vars) {
  const lang = (window.state && state.settings && state.settings.lang) || 'pt';
  const dict = I18N[lang] || I18N.pt;
  let str = dict[key] !== undefined ? dict[key] : (I18N.pt[key] !== undefined ? I18N.pt[key] : key);
  if (vars) {
    Object.keys(vars).forEach((k) => {
      str = String(str).replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
    });
  }
  return str;
}
