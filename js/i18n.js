function t(key, vars) {
  // BUG CORRIGIDO: "state" é declarado com let no app.js, o que NÃO o torna
  // propriedade de window — por isso "window.state" era sempre undefined e
  // t() caía sempre para português. Aqui referenciamos "state" diretamente
  // (visível porque ambos os scripts partilham o mesmo âmbito global).
  const lang = (typeof state !== 'undefined' && state.settings && state.settings.lang) || 'pt';
  const dict = I18N[lang] || I18N.pt;
  let str = dict[key] !== undefined ? dict[key] : (I18N.pt[key] !== undefined ? I18N.pt[key] : key);
  if (vars) {
    Object.keys(vars).forEach((k) => {
      str = String(str).replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
    });
  }
  return str;
}
